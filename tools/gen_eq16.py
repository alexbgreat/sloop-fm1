"""Tables of the 16-band graphic EQ (firmware/src/geq.h): python3 tools/gen_eq16.py > firmware/src/geq_tab.h

The EQ is a cascade of 16 bells, each a Simper (TPT) state-variable filter:  y = x + (A^2 - 1) * k * v1,  k = 1 / (A Q),
A = 10^(dB / 40). The bells overlap (about 0.58 octave apart), so they add in dB where they meet; the sliders are
therefore not the bells' own gains: EQ_MINV is the inverse of the interaction matrix (the response of bell j at the
centre of band i, dB per dB), the firmware multiplies the slider vector by it, and the result is what the bells get
(geq.h eq_solve). With it, equal sliders come out flat across the bands and one slider moved is that much at its
centre. Everything here is Q28 (the filter) or Q12 (the matrix); the firmware needs no float.
"""
import math

FS = 44100.0
Q = 1.5
FC = [40, 60, 90, 130, 200, 300, 440, 660, 980, 1450, 2200, 3250, 4800, 7200, 10700, 16000]
N = len(FC)
EMAX = 48          # bell gain table: -24 .. +24 dB in half-dB steps (index + EMAX)
SECANT_DB = 4.0    # the matrix is the secant of the response over this much gain


def bell(f, fc, gdb):
    a = 10 ** (gdb / 40.0)
    g = math.tan(math.pi * fc / FS)
    s = 1j * math.tan(math.pi * f / FS) / g
    return (s * s + s * a / Q + 1) / (s * s + s / (a * Q) + 1)


def resp_db(gains, f):
    h = 1
    for fc, x in zip(FC, gains):
        h *= bell(f, fc, x)
    return 20 * math.log10(abs(h))


def inverse(m):
    n = len(m)
    a = [row[:] + [1.0 if i == j else 0.0 for j in range(n)] for i, row in enumerate(m)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(a[r][c]))
        a[c], a[p] = a[p], a[c]
        d = a[c][c]
        a[c] = [x / d for x in a[c]]
        for r in range(n):
            if r != c:
                f = a[r][c]
                a[r] = [x - f * y for x, y in zip(a[r], a[c])]
    return [row[n:] for row in a]


def main():
    m = [[resp_db([SECANT_DB if j == k else 0 for k in range(N)], FC[i]) / SECANT_DB for j in range(N)] for i in range(N)]
    minv = inverse(m)
    q28 = 1 << 28
    out = []
    out.append("/* generated by tools/gen_eq16.py (Q = %.2f): do not edit */" % Q)
    out.append("#define EQ_Q_X100 %d" % round(Q * 100))
    out.append("#define EQ_EMAX %d" % EMAX)
    out.append("/* tan(pi fc / FS), Q28: the bells' centres %s Hz */" % " ".join(str(f) for f in FC))
    out.append("static const uint32_t EQ_G[%d] = {%s};" % (N, ", ".join("%du" % round(math.tan(math.pi * f / FS) * q28) for f in FC)))
    ks, bgs = [], []
    for e in range(-EMAX, EMAX + 1):
        a = 10 ** ((e / 2.0) / 40.0)
        k = 1.0 / (a * Q)
        ks.append(round(k * q28))
        bgs.append(round((a * a - 1.0) * k * q28))
    out.append("/* k = 1 / (A Q) for a bell of e/2 dB, e = -%d .. %d, Q28 */" % (EMAX, EMAX))
    out.append("static const uint32_t EQ_K[%d] = {\n    %s};" % (len(ks), ",\n    ".join(", ".join("%du" % x for x in ks[i:i + 8]) for i in range(0, len(ks), 8))))
    out.append("/* (A^2 - 1) k, the bell's weight on the band-pass, Q28 signed */")
    out.append("static const int32_t EQ_BG[%d] = {\n    %s};" % (len(bgs), ",\n    ".join(", ".join("%d" % x for x in bgs[i:i + 8]) for i in range(0, len(bgs), 8))))
    out.append("/* the inverse interaction matrix, Q12: bell gain i = sum over j of EQ_MINV[i][j] * slider j */")
    rows = []
    for row in minv:
        rows.append("    {" + ", ".join("%d" % round(x * 4096) for x in row) + "}")
    out.append("static const int16_t EQ_MINV[%d][%d] = {\n%s};" % (N, N, ",\n".join(rows)))
    print("\n".join(out))


if __name__ == "__main__":
    main()
