"""Tables of the 5-band parametric EQ (firmware/src/peq.h): python3 tools/gen_peq.py > firmware/src/peq_tab.h

Each band is a Simper (TPT) state-variable filter, y = m0 x + m1 v1 + m2 v2, its coefficients worked out on the device
from these tables (integers only: the firmware has no float):
  EQ_HZ10   the FREQ steps: the R40 preferred numbers (1/40 decade, ~1/12 octave), 20 Hz .. 16 kHz, in 0.1 Hz
  EQ_G      tan(pi f / FS) of each step, Q28
  EQ_QX100  the Q steps, x100;  EQ_QK: 1 / Q, Q28
  EQ_P      10^(i / 160), i = -96 .. 96, Q28: with e the gain in half dB, A = 10^(dB / 40) is EQ_P[2e], sqrt(A) EQ_P[e],
            A^2 EQ_P[4e] and 1 / A EQ_P[-2e] (indices + 96)
and, for the screen's response curve and spectrum (ui_peq.c):
  EQ_TX     tan(pi f / FS) at the centre of each of the 240 columns (20 Hz .. 20 kHz, logarithmic), Q20
  EQ_XB     the FFT bin (512 points at FS / 2: 43.07 Hz a bin) at the left edge of each column (and the right edge of
            the last), Q4
  EQ_L2     log2(1 + i / 64), i = 0 .. 64, Q12 (peq.h eq_log2)
"""
import math

FS = 44100.0
R40 = [1.00, 1.06, 1.12, 1.18, 1.25, 1.32, 1.40, 1.50, 1.60, 1.70, 1.80, 1.90, 2.00, 2.12, 2.24, 2.36, 2.50, 2.65,
       2.80, 3.00, 3.15, 3.35, 3.55, 3.75, 4.00, 4.25, 4.50, 4.75, 5.00, 5.30, 5.60, 6.00, 6.30, 6.70, 7.10, 7.50,
       8.00, 8.50, 9.00, 9.50]
HZ = [R40[(j + 12) % 40] * 10 ** (1 + (j + 12) // 40) for j in range(117)]   # 20 Hz .. 16 kHz
QS = [0.30, 0.35, 0.40, 0.45, 0.50, 0.56, 0.63, 0.71, 0.80, 0.90, 1.00, 1.10, 1.25, 1.40, 1.60, 1.80, 2.00, 2.20,
      2.50, 2.80, 3.20, 3.60, 4.00, 4.50, 5.00, 5.60, 6.30, 7.10, 8.00]
COLS = 240
F_LO, F_HI = 20.0, 20000.0
BIN = FS / 2 / 512


def col_hz(x):                       # the column's centre
    return F_LO * (F_HI / F_LO) ** (x / (COLS - 1))


def rows(name, ctype, vals, per=8):
    out = ['static const %s %s[%d] = {' % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')
    return '\n'.join(out)


def main():
    q28 = 1 << 28
    print('/* generated by tools/gen_peq.py: do not edit */')
    print('#define EQ_NF %d' % len(HZ))
    print('#define EQ_NQ %d' % len(QS))
    print('#define EQ_COLS %d' % COLS)
    print('/* the FREQ steps (R40, 0.1 Hz) and tan(pi f / FS), Q28 */')
    print(rows('EQ_HZ10', 'uint32_t', [int(round(h * 10)) for h in HZ]))
    print(rows('EQ_G', 'uint32_t', [int(round(math.tan(math.pi * h / FS) * q28)) for h in HZ]))
    print('/* the Q steps (x100) and 1 / Q, Q28 */')
    print(rows('EQ_QX100', 'uint16_t', [int(round(q * 100)) for q in QS]))
    print(rows('EQ_QK', 'uint32_t', [int(round(q28 / q)) for q in QS]))
    print('/* 10^(i / 160), i = -96 .. 96, Q28 */')
    print(rows('EQ_P', 'uint32_t', [int(round(10 ** (i / 160.0) * q28)) for i in range(-96, 97)]))
    print('/* the screen: tan(pi f / FS) at each column, Q20; the FFT bin at each column edge, Q4; log2(1 + i / 64), Q12 */')
    print(rows('EQ_TX', 'uint32_t', [int(round(math.tan(math.pi * col_hz(x) / FS) * (1 << 20))) for x in range(COLS)]))
    edges = [F_LO * (F_HI / F_LO) ** ((x - 0.5) / (COLS - 1)) for x in range(COLS + 1)]
    print(rows('EQ_XB', 'uint16_t', [min(int(round(e / BIN * 16)), 65535) for e in edges], 12))
    print(rows('EQ_L2', 'uint16_t', [int(round(math.log2(1 + i / 64.0) * 4096)) for i in range(65)], 12))


if __name__ == '__main__':
    main()
